"""3편 자동 플레이"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'shared'))
from playtest_core import Tester
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
t = Tester(ROOT, sys.argv[1], sys.argv[2], 'ep3/index.html')
t.goto(0.3, 3.6); t.aim(0.94, 1.2, 3.6); t.use('toolbox')
t.check('bar' in t.state('inv'), '쇠지렛대')
t.goto(0, 0.8); t.aim(-2.2, 1.6, -3.2); t.shot('02_lab')
t.goto(-3.9, 0.6); t.aim(-3.9, 0.6, 1.33); t.use('desk', '03_note')
t.goto(-4.2, 0.8); t.aim(-4.97, 1.5, 0.8); t.use('poster', '04_poster')
t.goto(1.3, 1.2); t.aim(1.3, 1.45, 1.97); t.use('signin')
t.goto(-4.6, -1.7); t.aim(-4.97, 1.6, -3.1); t.use('whiteboard')
t.goto(4.8, -0.8); t.aim(5.4, 1.5, -0.03); t.use('report')
t.goto(5.0, -2.6); t.aim(5.0, 1.0, -3.49); t.use('t3', close=False); t.wait_link()
t.send('사고 조사'); t.esc(); t.wait(1500)
t.goto(4.8, -0.8); t.aim(5.4, 1.5, -0.03); t.use('report', '05_report_changed')
t.goto(5.0, -2.6); t.aim(5.0, 1.0, -3.49); t.use('t3', close=False); t.send('포스터'); t.shot('06_lines'); t.esc()
t.check(t.state('k.k_lines') == True, '포스터 5~8줄 받음')
t.pg.evaluate('window.__game.ctx.__decode()'); t.wait(400)
ans = t.pg.evaluate("import('/ep3/js/content.js').then(m => m.ANSWER)")
for ch in '범인마기사해치': t.pbtn(ch)
t.pbtn('이대로'); t.check(t.state('k.k_decoded') != True, '절반만 적으면 안 풀림')
for ch in '금고회선만': t.pbtn(ch)
t.pbtn('이대로'); t.shot('07_decoded'); t.esc()
t.check(t.state('k.k_decoded') == True, '수첩 해독 (' + ans + ')')
t.goto(5.0, -2.6); t.aim(5.0, 1.0, -3.49); t.use('t3', close=False); t.send('해독'); t.shot('08_decoded_sent'); t.esc()
t.goto(5.6, -0.6); t.aim(6.3, 1.0, -2.2); t.use('panel')
t.goto(4.4, -0.55); t.aim(4.4, 0.3, -1.6); t.use('cabinet'); t.wait(1200)
t.check(t.state('hatchShown'), '해치 드러남')
t.goto(4.4, -0.7); t.aim(4.4, 0.03, -1.5); t.use('hatch', close=False); t.btn(0); t.wait(300)
t.keys('9504'); t.check(not t.state('done'), '윤서경 사번은 오답')
t.keys('9107'); t.wait(5000); t.check(t.state('done'), '점검구로'); t.shot('09_ending')
t.check(3 in t.cleared(), '3편 완료 기록')
t.end()
