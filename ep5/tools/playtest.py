"""5편 자동 플레이"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'shared'))
from playtest_core import Tester
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
t = Tester(ROOT, sys.argv[1], sys.argv[2], 'ep5/index.html')
def term(): t.goto(-0.3, -1.6); t.aim(-1.1, 1.0, -1.6); t.use('t5', close=False); t.wait_link()
def jack(n): t.goto(-0.8, -0.55); t.aim(-1.56, 1.35, -0.55); t.use('patch', close=False); t.pbtn(f'{n}번 잭'); t.esc()
def code(s): t.pbtn('네 자리'); t.keys(s, enter=False); t.pg.keyboard.press('Enter'); t.wait(600); t.wait_link()
t.goto(-1.0, 2.6); t.aim(0.5, 1.2, -1.0); t.shot('02_ante_soot')
t.goto(-2.3, 1.0); t.aim(-2.93, 1.3, 1.0); t.use('junction'); t.check(t.state('power'), '금고 전원')
t.goto(-2.1, 1.3); t.aim(-2.1, 1.5, 0.03); t.use('plaque', '03_plaque')
t.goto(-2.5, 3.1); t.aim(-2.5, 0.35, 2.56); t.use('pumptag')
t.goto(-1.9, 1.5); t.aim(-1.9, 0.2, 0.7); t.use('toolbox'); t.check('mirror' in t.state('inv'), '점검 거울')
mp = t.pg.evaluate('(() => { const v = new window.__game.ctx.THREE.Vector3(); window.__game.ctx.refs.mech.getWorldPosition(v); return [v.x, v.y, v.z]; })()')
t.goto(mp[0] - 0.9, mp[2]); t.aim(mp[0], mp[1] - 0.1, mp[2]); t.use('mech')
t.check(t.state('k.k_dial') != True, '뒤판이 막혀 있어 아직 못 읽음')
term(); t.shot('04_fake'); code('1111'); t.check('안 열려요' in t.last(), '틀린 번호 → 안 열림'); t.esc()
jack(4); term(); t.shot('05_real_first')
t.send('2026년'); t.send('메인 회선'); t.send('어떻게'); t.shot('06_real'); t.esc(); t.wait(1500)
t.check(t.state('coverOff'), '뒤판이 풀림')
t.goto(mp[0] - 0.9, mp[2]); t.aim(mp[0], mp[1] - 0.1, mp[2]); t.use('mech', '07_mirror')
t.check(t.state('k.k_dial') == True, '거울로 바퀴 읽음')
jack(1); term(); code('3185'); t.wait(2500); t.shot('08_badend')
t.check(t.state('lost'), '진짜 번호를 주면 나쁜 결말')
t.pg.evaluate("document.querySelector('#badend-lines button').click()"); t.wait(500); t.lock()
t.check(not t.state('lost'), '되돌리기')
term(); code('5813'); t.shot('09_trap'); t.esc(); t.wait(6000)
t.check(t.state('trapped'), '협박 번호로 덫')
t.goto(-1.0, 2.6); t.aim(0.5, 1.2, -1.0); t.shot('10_ante_clean')
t.goto(8.6, 3.3); t.aim(9.34, 1.1, 3.3); t.use('gate')
jack(4); term(); t.send('어떻게 됐나'); t.send('철문'); code('1234'); t.check(not t.state('gateOpen'), '1234 오답'); code('9107'); t.shot('11_lock'); t.esc(); t.wait(1500)
t.check(t.state('gateOpen'), '철문 열림')
t.goto(8.3, 3.0); t.aim(8.9, 0.1, 3.0); t.use('tinbox', '12_box')
t.goto(8.5, 3.3); t.aim(10, 1.2, 3.3); t.shot('13_gate_open')
t.goto(9.9, 3.3); t.wait(6000); t.check(t.state('done'), '터널 밖으로'); t.shot('14_ending')
t.pg.mouse.click(640, 200); t.wait(800); t.shot('15_ending_all', True)
t.check(5 in t.cleared(), '5편 완료 기록')
t.end()
